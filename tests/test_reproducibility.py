"""Brief criterion 1 (reproducible) and the dependency restriction of the brief.

The notebook is executed twice in a copy of the working tree, so the repository
is not modified. The contract command is `uv run jupyter nbconvert ...`; here
`jupyter` runs from the interpreter that runs pytest, which is the same uv
environment, to avoid a nested `uv run`.
"""

import re
import shutil
import subprocess
import sys
import tomllib

import pytest
from helpers import PROCESSED, ROOT, T7_OUTPUTS

RUN_TIMEOUT_S = 30 * 60  # T7: escalate to Mai if a run takes longer
MAIN_DEPENDENCIES = {
    "ipykernel",
    "jupyter",
    "matplotlib",
    "numpy",
    "pandas",
    "scikit-learn",
    "seaborn",
}
IGNORED = shutil.ignore_patterns(
    ".git", ".venv", ".ruff_cache", ".pytest_cache", "__pycache__", ".ipynb_checkpoints"
)


def execute_notebook(workdir, output) -> dict:
    """Delete the T7 outputs, run the notebook, collect the outputs as bytes."""
    for name in T7_OUTPUTS:
        (workdir / "data" / "processed" / name).unlink(missing_ok=True)
    cmd = [
        sys.executable,
        "-m",
        "jupyter",
        "nbconvert",
        "--to",
        "notebook",
        "--execute",
        "classification.ipynb",
        "--output",
        str(output),
    ]
    proc = subprocess.run(
        cmd, cwd=workdir, capture_output=True, text=True, timeout=RUN_TIMEOUT_S
    )
    outputs = {}
    for name in T7_OUTPUTS:
        path = workdir / "data" / "processed" / name
        outputs[name] = path.read_bytes() if path.is_file() else None
    return {"returncode": proc.returncode, "stderr": proc.stderr[-3000:], **outputs}


@pytest.fixture(scope="module")
def two_runs(tmp_path_factory):
    base = tmp_path_factory.mktemp("criterion1")
    workdir = base / "repo"
    shutil.copytree(ROOT, workdir, ignore=IGNORED)
    first = execute_notebook(workdir, base / "run1.ipynb")
    if first["returncode"] != 0:
        return first, None
    return first, execute_notebook(workdir, base / "run2.ipynb")


def assert_ran(run) -> None:
    assert run is not None, "the second run was not attempted"
    assert run["returncode"] == 0, f"notebook failed:\n{run['stderr']}"


def test_notebook_runs_and_writes_every_contract_output(two_runs):
    """Criterion 1: the command runs end to end and writes the T7 outputs."""
    first, _ = two_runs
    assert_ran(first)
    missing = [name for name in T7_OUTPUTS if first[name] is None]
    assert not missing, f"not written: {missing}"


def test_two_runs_are_byte_identical(two_runs):
    """Criterion 1: two consecutive runs give byte-identical T7 outputs."""
    first, second = two_runs
    assert_ran(first)
    assert_ran(second)
    differ = [name for name in T7_OUTPUTS if first[name] != second[name]]
    assert not differ, f"differ between runs: {differ}"


def test_repository_outputs_are_what_the_command_produces(two_runs):
    """Criterion 1: the outputs in data/processed/ are regenerated by the command.

    Guards the other tests, which read the files in the repository.
    """
    first, _ = two_runs
    assert_ran(first)
    stale = [
        name
        for name in T7_OUTPUTS
        if not (PROCESSED / name).is_file()
        or (PROCESSED / name).read_bytes() != first[name]
    ]
    assert not stale, f"missing or stale in data/processed/: {stale}"


def test_lockfile_is_consistent_with_pyproject():
    """Criterion 1: 'uv sync --locked' requires uv.lock to match pyproject.toml."""
    proc = subprocess.run(
        ["uv", "lock", "--check"], cwd=ROOT, capture_output=True, text=True
    )
    assert proc.returncode == 0, proc.stderr


def dependency_names(specs: list[str]) -> set[str]:
    return {re.split(r"[\s<>=!~;\[]", spec, maxsplit=1)[0].lower() for spec in specs}


def test_declared_dependencies():
    """Brief 'Restricciones': only pytest (dev) and scipy (explicit) are added."""
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    runtime = dependency_names(pyproject["project"]["dependencies"])
    assert runtime == MAIN_DEPENDENCIES | {"scipy"}
    dev = dependency_names(pyproject.get("dependency-groups", {}).get("dev", []))
    assert dev == {"pytest"}
